_repl_sorted = sorted(neutralize_repl.items(), key=lambda x: -len(x[0]))

SN_PLACEHOLDER = "___SN___"

def neutralize(text):
    if not text: return text
    was_upper = text[0].isupper()
    text = re.sub(r'«Одноклассниках»', SN_PLACEHOLDER, text)
    text = re.sub(r'«Одноклассников»', SN_PLACEHOLDER, text)
    text = re.sub(r'в\s+Одноклассниках', "в " + SN_PLACEHOLDER, text)
    for old, new in _repl_sorted:
        def make_repl(m, o=old, n=new):
            if m.group(0)[0].isupper():
                return n[0].upper() + n[1:]
            return n
        text = re.sub(r'\b' + re.escape(old) + r'\b', make_repl, text, flags=re.IGNORECASE)
    text = text.replace(SN_PLACEHOLDER, "«Одноклассниках»")
    if was_upper and text:
        text = text[0].upper() + text[1:]
    return text


