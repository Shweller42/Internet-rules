def strip_articles(text):
    for pat in [r'\s*\([^)]*ст\.\s*\d+[^)]*\)', r'\s*по\s+ст\.?\s*\d+[\d,\s\-]*(?:УК\s*РБ)?',
                 r'\s*\(УК\s*РБ[^)]*\)', r'\s*\([^)]*УК\s*РБ[^)]*\)', r'\(КоАП[^)]*\)',
                 r'\s*Закон[^)]*\)']:
        text = re.sub(pat, '', text)
    return text.strip()

def shorten_to(text, target=72, min_len=55):
    text = strip_articles(text).strip()
    if len(text) <= target + 15:
        return text if text[-1] in '.!?' else text + '.'
    sentences = [s.strip() for s in re.split(r'(?<=[.!])\s+', text) if s.strip()]
    result = sentences[0] if sentences else text
    for i in range(1, len(sentences)):
        candidate = result + " " + sentences[i]
        if len(candidate) <= target + 8:
            result = candidate
        else:
            break
    if len(result) > target + 8:
        preps = [' без ', ' в ', ' во ', ' до ', ' для ', ' за ', ' из ', ' изо ', ' к ', ' ко ', ' на ',
                 ' над ', ' надо ', ' о ', ' об ', ' обо ', ' от ', ' ото ', ' по ', ' под ', ' подо ',
                 ' при ', ' про ', ' ради ', ' с ', ' со ', ' у ', ' через ', ' чрез ']
        while True:
            cut = result.rfind(' ', 0, target + 1)
            if cut <= 0:
                break
            candidate = result[:cut]
            okay = True
            for p in preps:
                if candidate.endswith(p.strip()):
                    okay = False
                    break
            conj = [' и', ' а', ' но', ' или', ' да', ' что', ' чтобы', ' если']
            for c in conj:
                if candidate.endswith(c):
                    okay = False
                    break
            if okay:
                result = candidate
                break
            result = candidate
        if len(result) < min_len:
            result = text[:min(len(text), target)]
    result = result.rstrip()
    result = re.sub(r'[—\-:,;]\s*$', '', result).rstrip()
    result = re.sub(r'[—\-]\s*\w{0,8}$', '', result).rstrip()
    result = re.sub(r':\s*\w{0,8}$', '.', result).rstrip()
    preps = [' без', ' в', ' во', ' до', ' для', ' за', ' из', ' изо', ' к', ' ко', ' на',
             ' над', ' надо', ' о', ' об', ' обо', ' от', ' ото', ' по', ' под', ' подо',
             ' при', ' про', ' ради', ' с', ' со', ' у', ' через', ' чрез']
    for p in preps:
        if result.endswith(p):
            result = result[:-len(p)].rstrip()
            break
    # If text ends with preposition+word where word is an incomplete adjective (крайней)
    # strip it. But only if the word after prep looks incomplete (< 5 chars or no noun ending)
    words = result.split()
    if len(words) >= 2 and words[-1].rstrip('.!?').isalpha():
        second_last = ' ' + words[-2]
        last_word_clean = words[-1].rstrip('.!?')
        if second_last == ' без' and len(last_word_clean) <= 8:
            # "без Х" where Х is a short word — probably needs more context
            result = result.rstrip()
            stripped = ' ' + words[-1]
            if result.endswith(stripped):
                result = result[:-len(stripped)].rstrip()
                result = result[:-4].rstrip()  # strip " без"
    result = result.rstrip(',;')
    if not result[-1] in '.!?':
        result += '.'
    return result

