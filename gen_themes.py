def pick_wrongs(pool, correct_len, used):
    available = [w for w in pool if w not in used]
    if len(available) < 3:
        used.clear()
        available = list(pool)
    random.shuffle(available)

    target_min = correct_len - 15
    target_max = correct_len - 2

    candidates = [(w, len(w)) for w in available if target_min <= len(w) <= target_max]

    if len(candidates) < 3:
        candidates = [(w, len(w)) for w in available if target_min <= len(w) <= correct_len + 5]

    if len(candidates) < 3:
        candidates = [(w, len(w)) for w in available]

    candidates.sort(key=lambda x: abs(x[1] - (correct_len - 8)))
    result = [w for w, l in candidates[:3]]

    max_w = max(len(w) for w in result)
    if correct_len >= max_w:
        for w in available:
            if w not in result and len(w) >= max_w and len(w) <= correct_len + 8:
                min_w = min(result, key=len)
                result[result.index(min_w)] = w
                break

    max_w = max(len(w) for w in result)
    if correct_len >= max_w and len(available) > 3:
        extras = [w for w in available if w not in result]
        extras.sort(key=lambda w: (abs(len(w) - correct_len + 5), 0 if len(w) < correct_len else 1))
        for w in extras:
            if len(w) > max_w and len(w) <= correct_len + 3 and len(w) >= correct_len - 15:
                min_w = min(result, key=len)
                result[result.index(min_w)] = w
                max_w = max(len(w) for w in result)
                if correct_len < max_w:
                    break

    used.extend(result)
    return result


